import type {
  BodyStyle,
  Car,
  CarAvailability,
  CarCondition,
  CarSpec,
  FuelType,
  TransmissionType,
} from "@/types";
import { brands } from "./brands.mock";
import { categories } from "./categories.mock";
import { unsplash } from "./shared/unsplash";

function findBrand(slug: string) {
  const brand = brands.find((b) => b.slug === slug);
  if (!brand) throw new Error(`Unknown brand slug in car seed: ${slug}`);
  return brand;
}

function findCategory(slug: string) {
  const category = categories.find((c) => c.slug === slug);
  if (!category) throw new Error(`Unknown category slug in car seed: ${slug}`);
  return category;
}

interface CarSeed {
  slug: string;
  brandSlug: string;
  categorySlug: string;
  model: string;
  trim?: string;
  year: number;
  price: number;
  mileage: number;
  fuelType: FuelType;
  transmission: TransmissionType;
  bodyStyle: BodyStyle;
  condition: CarCondition;
  availability: CarAvailability;
  exteriorColor: string;
  interiorColor: string;
  seats: number;
  horsepower: number;
  topSpeedMph: number;
  zeroToSixtySec: number;
  shortDescription: string;
  description: string;
  photoIds: string[];
  isFeatured?: boolean;
  createdAt: string;
}

function buildSpecs(seed: CarSeed): CarSpec[] {
  const efficiency: CarSpec =
    seed.fuelType === "electric"
      ? { label: "Est. Range", value: "320 mi", group: "efficiency" }
      : seed.fuelType === "hybrid"
        ? { label: "Combined Economy", value: "42 mpg", group: "efficiency" }
        : { label: "Combined Economy", value: "19 mpg", group: "efficiency" };

  return [
    { label: "Horsepower", value: `${seed.horsepower} hp`, group: "performance" },
    { label: "0–60 mph", value: `${seed.zeroToSixtySec}s`, group: "performance" },
    { label: "Top Speed", value: `${seed.topSpeedMph} mph`, group: "performance" },
    { label: "Transmission", value: formatTransmission(seed.transmission), group: "performance" },
    { label: "Seating", value: `${seed.seats} seats`, group: "interior" },
    { label: "Interior", value: seed.interiorColor, group: "interior" },
    { label: "Body Style", value: formatBodyStyle(seed.bodyStyle), group: "dimensions" },
    { label: "Driver Assistance", value: "Adaptive cruise, lane keep, 360° camera", group: "safety" },
    efficiency,
  ];
}

function formatTransmission(t: TransmissionType): string {
  switch (t) {
    case "dual-clutch":
      return "Dual-Clutch Automatic";
    case "cvt":
      return "CVT Automatic";
    default:
      return t.charAt(0).toUpperCase() + t.slice(1);
  }
}

function formatBodyStyle(b: BodyStyle): string {
  return b.charAt(0).toUpperCase() + b.slice(1);
}

function buildCar(seed: CarSeed): Car {
  const brand = findBrand(seed.brandSlug);
  const category = findCategory(seed.categorySlug);
  const name = `${seed.year} ${brand.name} ${seed.model}${seed.trim ? ` ${seed.trim}` : ""}`;

  return {
    id: `car-${seed.slug}`,
    slug: seed.slug,
    brand,
    category,
    model: seed.model,
    trim: seed.trim,
    year: seed.year,
    price: seed.price,
    currency: "USD",
    mileage: seed.mileage,
    fuelType: seed.fuelType,
    transmission: seed.transmission,
    bodyStyle: seed.bodyStyle,
    condition: seed.condition,
    availability: seed.availability,
    exteriorColor: seed.exteriorColor,
    interiorColor: seed.interiorColor,
    horsepower: seed.horsepower,
    topSpeedMph: seed.topSpeedMph,
    zeroToSixtySec: seed.zeroToSixtySec,
    shortDescription: seed.shortDescription,
    description: seed.description,
    images: seed.photoIds.map((photoId, index) => ({
      id: `${seed.slug}-img-${index + 1}`,
      url: unsplash(photoId, 1600),
      alt: `${name} — photo ${index + 1}`,
      isPrimary: index === 0,
      order: index,
    })),
    specs: buildSpecs(seed),
    isFeatured: seed.isFeatured ?? false,
    vin: `MOCK${seed.slug.toUpperCase().replace(/-/g, "").slice(0, 13)}`,
    createdAt: seed.createdAt,
    updatedAt: seed.createdAt,
  };
}

